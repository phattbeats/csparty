// PHA-4091: hub assertion check (node test/phattid_test.mjs)
import assert from "node:assert/strict";
import { verifyAssertion, assertedMember, _resetKeyCache } from "../src/phattid.js";
const kp = await crypto.subtle.generateKey({ name: "Ed25519" }, true, ["sign", "verify"]);
const pub = await crypto.subtle.exportKey("jwk", kp.publicKey);
const b = (u) => Buffer.from(u).toString("base64url");
const sign = async (c) => { const body = b(JSON.stringify(c)); return `pa1.${body}.${b(await crypto.subtle.sign({ name: "Ed25519" }, kp.privateKey, new TextEncoder().encode("pa1." + body)))}`; };
const t = Math.floor(Date.now() / 1000), aud = "lobby.example";
const good = await sign({ sub: "arc-1", aud, iat: t, exp: t + 300, display: "Brandy" });
assert.equal((await verifyAssertion(good, pub, { aud })).sub, "arc-1");
assert.equal(await verifyAssertion(good, pub, { aud: "other" }), null, "wrong aud");
assert.equal(await verifyAssertion(await sign({ sub: "a", aud, iat: t - 900, exp: t - 1 }), pub, { aud }), null, "expired");
assert.equal(await verifyAssertion(good.slice(0, -3) + "AAA", pub, { aud }), null, "bad sig");
const env = { PHATT_HUB: "https://hub.example" };
const fetchImpl = async () => new Response(JSON.stringify(pub));
_resetKeyCache();
assert.deepEqual(await assertedMember(good, env, aud, fetchImpl), { arcadeId: "arc-1", display: "Brandy" });
assert.equal(await assertedMember(good, {}, aud, fetchImpl), null, "hub unset = guest");
assert.equal(await assertedMember("", env, aud, fetchImpl), null, "no token = guest");
console.log("phattid ok");
